# ==================== إعداد البوت ====================
logging.basicConfig(
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    level=logging.INFO
)
logger = logging.getLogger(__name__)

# متغيرات الحالة
current_index = 0
is_posting = False
posted_count = 0

def get_next_content():
    """الحصول على المحتوى التالي بالترتيب"""
    global current_index
    content = ALL_CONTENT[current_index % len(ALL_CONTENT)]
    current_index += 1
    return content

def get_footer():
    """توليد تذييل المنشور"""
    footers = [
        "\n\n🌟 *@ActiveOneWear* | للمزيد تابعونا 🌹",
        "\n\n💚 *@ActiveOneWear* | محتوى إسلامي يومي ✨",
        "\n\n📿 *@ActiveOneWear* | شاركنا الأجر 🤍",
        "\n\n🕌 *@ActiveOneWear* | نشرٌ للخير دائمًا 🌿",
    ]
    return random.choice(footers)

async def post_to_group(bot: Bot) -> bool:
    """نشر محتوى في المجموعة"""
    global posted_count
    try:
        content_item = get_next_content()
        message = content_item["content"] + get_footer()
        
        await bot.send_message(
            chat_id=GROUP_USERNAME,
            text=message,
            parse_mode='Markdown'
        )
        posted_count += 1
        logger.info(f"✅ تم النشر #{posted_count} | النوع: {content_item['type']}")
        return True
    except TelegramError as e:
        logger.error(f"❌ خطأ في النشر: {e}")
        return False

async def auto_post_job(context: ContextTypes.DEFAULT_TYPE):
    """وظيفة النشر التلقائي"""
    if is_posting:
        await post_to_group(context.bot)

